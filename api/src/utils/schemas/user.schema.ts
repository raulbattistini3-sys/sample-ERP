import { z } from "zod";
import permissoesUsuarioEnum, {
    PermissoesUsuarioEnum,
} from "../../enums/usuarios_permissoes.enum";

const userPermissoes = permissoesUsuarioEnum.options.join(", ");

const UserSchema = z.object({
    id: z.string().uuid().nonempty("É necessário prover um ID"),
    nome: z.string().nonempty("É preciso prover um nome."),
    permissoes: z
        .string()
        .refine(
            (value) =>
                permissoesUsuarioEnum.options.includes(
                    value as PermissoesUsuarioEnum
                ),
            {
                message: `As permissões permitidas são ${userPermissoes} `,
            }
        ),
    email: z.string().nonempty("É necessário prover um email."),
    senha: z.string().nonempty("É necessário prover uma senha."),
    ativo: z.boolean().default(true),
});

// POST /user/register (public): permissoes/ativo in the body are ignored, the service
// always creates an active Estoque usuario
export const RegisterUserSchema = UserSchema.pick({ nome: true, email: true, senha: true });

// POST /user (ADM): id is generated by the database; permissoes falls back to Estoque
export const CreateUserSchema = UserSchema.omit({ id: true }).extend({
    permissoes: UserSchema.shape.permissoes.default(
        permissoesUsuarioEnum.Values.Estoque
    ),
});

// PUT /user/:id (ADM): id comes from the URL; senha only when it's being changed
export const UpdateUserSchema = UserSchema.omit({ id: true, senha: true }).extend({
    ativo: z.boolean().optional(),
    senha: z.string().nonempty("A nova senha não pode ser vazia.").optional(),
});

export const LoginUserSchema = UserSchema.pick({ email: true, senha: true });

export default UserSchema;